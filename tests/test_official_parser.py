def test_parse_banzuke_real_format():
    cards = parse_banzuke(SAMPLE_BANZUKE)
    assert len(cards) == 2, f"expected 2 races, got {len(cards)}"
    c = cards[0]
    assert c.race_date == "20240815"
    assert c.venue_code == "21"  # 芦屋
    assert c.race_no == 1
    assert len(c.entries) == 6, f"expected 6 entries, got {len(c.entries)}: {c.entries}"

    e1 = c.entries[0]
    assert e1.lane == 1
    assert e1.racer_id == "5018"
    assert e1.name == "竹下大樹"
    assert e1.age == 25
    assert e1.branch == "福岡"
    assert e1.weight == 54.0
    assert e1.grade == "A2"
    assert e1.win_rate_national == 6.32
    assert e1.place_rate_national == 45.97
    assert e1.win_rate_local == 4.76
    assert e1.place_rate_local == 23.53
    assert e1.motor_no == 40
    assert e1.motor_2rate == 30.12
    assert e1.boat_no == 12
    assert e1.boat_2rate == 36.49

    # 6艇目（名前に全角空白入り → "齊藤廉" に正規化される）
    e6 = c.entries[5]
    assert e6.lane == 6
    assert e6.racer_id == "5351"
    assert e6.name == "齊藤廉"
    assert e6.grade == "B2"


def test_parse_results_real_format():
    results = parse_results(SAMPLE_RESULT)
    assert len(results) == 2
    r1 = results[0]
    assert r1.race_date == "20240815"
    assert r1.venue_code == "12"  # 住之江
    assert r1.race_no == 1
    assert len(r1.rows) == 6

    # 1着 lane=4, racer 3963
    winner = next(row for row in r1.rows if row.rank == 1)
    assert winner.lane == 4
    assert winner.racer_id == "3963"
    # レースタイム 1.52.9 = 1*60 + 52 + 0.9 = 112.9
    assert abs(winner.race_time_sec - 112.9) < 1e-6
    # ST 0.11
    assert abs(winner.start_timing - 0.11) < 1e-6

    # 払戻（連複も "-" 区切り）
    assert ("4", 640) in r1.payouts.get("win", [])
    assert ("4", 330) in r1.payouts.get("place", [])
    assert ("2", 210) in r1.payouts.get("place", [])
    assert ("4-2", 2580) in r1.payouts.get("exacta", [])
    assert ("2-4", 1130) in r1.payouts.get("quinella", [])
    assert ("4-2-1", 7530) in r1.payouts.get("trifecta", [])
    assert ("1-2-4", 350) in r1.payouts.get("trio", [])
    # 拡連複3点
    wide = r1.payouts.get("wide", [])
    assert ("2-4", 210) in wide
    assert ("1-4", 190) in wide
    assert ("1-2", 200) in wide

    # 2レース目も成立
    r2 = results[1]
    assert r2.race_no == 2
    assert ("1-4-6", 14380) in r2.payouts.get("trifecta", [])
